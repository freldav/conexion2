    public void populateJtable(){
    controlador.users user= new controlador.users();
    //userList=user.userslist();
    this. userList = user.usersList();
    String[] colName={"id","nombre","apellido","contrasena","email","telefono","genero","Imagen"};
    
    Object[][] rows= new Object[userList.size()][8];
    //debe ser con la secuencia del contructor user 
    for(int i=0;i<userList.size();i++){
        rows[i][0]=userList.get(i).getId();
        rows[i][1]=userList.get(i).getNombre();
        rows[i][2]=userList.get(i).getApellido();
     rows[i][3]=userList.get(i).getContrasena();
     rows[i][4]=userList.get(i).getEmail();
     rows[i][5]=userList.get(i).getTelefono();
     rows[i][6]=userList.get(i).getGenero();
     //manejo de la imagen en la tabla no desde la base de datos
     
     ImageIcon pic= new ImageIcon(new ImageIcon(userList.get(i).getImagen()).getImage()
     .getScaledInstance(120,80,Image.SCALE_SMOOTH));
    rows[i][7]=pic;
    
    }
    modelo.MyTableModel mmd= new modelo.MyTableModel(rows,colName);
   // JTable1.setModel(model);
    jTable1_users.setModel(mmd);
    jTable1_users.setRowHeight(90);
    jTable1_users.getColumnModel().getColumn(7).setPreferredWidth(90);
    
    }
