      public void populateordenesJtable(){
    controlador.ordenes ordenes= new controlador.ordenes();
    
   ArrayList<controlador.ordenes> ordenesList=ordenes.ordenesList();
   
    String[] colName={"id","nombre","precio", "cantidad","valor"};
     
    Object[][] rows = new Object[ordenesList.size()][colName.length];
    
    DefaultTableModel model=(DefaultTableModel)jTable1_ordenes.getModel();
    if(ordenesList==null || ordenesList.isEmpty()){
    model.setRowCount(0);
    model.setColumnIdentifiers(colName);
    
    }
    
    for(int i=0; i<ordenesList.size();i++){
    rows[i][0]=ordenesList.get(i).getId();
    rows[i][1]=ordenesList.get(i).getNombre();
    rows[i][2]=ordenesList.get(i).getPrecios();
    rows[i][3]=ordenesList.get(i).getCantidad();
    rows[i][4]=ordenesList.get(i).getValor();
    }
    model.setDataVector(rows,colName);
   jTable1_ordenes.setModel(model);
    
    }
