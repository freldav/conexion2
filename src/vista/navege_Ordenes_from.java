    private void jButton1_productoordenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_productoordenActionPerformed
        // TODO add your handling code here:
        Integer cantidad;
        int rowindex;
        try{
        cantidad= Integer.valueOf(JOptionPane.showInputDialog("cuantos desea","1"));
        
        rowindex=jTable1_productos.getSelectedRow();
        if(rowindex == -1){ 
        JOptionPane.showMessageDialog(null,"selecione primero","atencion" ,JOptionPane.WARNING_MESSAGE);
        }
        boolean isExist= false;
        int index=0;
        Object[] rowData= new Object[5];
        rowData[0]=jTable1_productos.getValueAt(rowindex ,0);
         rowData[1]=jTable1_productos.getValueAt(rowindex,1);
        rowData[2]=jTable1_productos.getValueAt(rowindex,2);
        rowData[3]=cantidad;
        Double precio= Double.valueOf(jTable1_productos.getValueAt(rowindex, 2).toString());
        rowData[4]=cantidad * precio;
        DefaultTableModel model=(DefaultTableModel)jTable1_ordenes.getModel();
        if(cantidad> Integer.valueOf(jTable1_productos.getValueAt(rowindex,0).toString()))
        {
        JOptionPane.showMessageDialog(null,"cantidad no disponible","valor no valido",2);
        }
        else if(cantidad == 0)
                {
        JOptionPane.showMessageDialog(null,"cantidad no puede ser cero","valor  invalido",2);
                }
        else{
            if(jTable1_ordenes.getModel().getRowCount()==0)
        { model.addRow(rowData);
            getTotal();
        }
        else{
        for(int i = 0; i<jTable1_ordenes.getModel().getRowCount(); i++)
        {
            if(rowData[0].toString().equals(jTable1_ordenes.getValueAt(i,0).toString()))
        {  isExist= true;
        index=i;
        break;
        }
   }
        if(isExist){
        Integer newcantidad = cantidad + Integer.valueOf(jTable1_ordenes.getValueAt(index,3).toString());
       if(newcantidad > Integer.valueOf(jTable1_productos.getValueAt(rowindex,3).toString()))
        {
        JOptionPane.showMessageDialog(null,"cantidad no disponible","valor no valido",2);
        } else{
        jTable1_ordenes.setValueAt(newcantidad, index, 3);
        jTable1_ordenes.setValueAt(newcantidad*precio, index, 4);
        getTotal();
        }  
       }
        else{
        
        model.addRow(rowData);
        getTotal();
        }
        }
        }
        }catch( HeadlessException | NumberFormatException ex){
        JOptionPane.showMessageDialog(null,ex.getMessage(),"error",1);
        }
    }//GEN-LAST:event_jButton1_productoordenActionPerformed

