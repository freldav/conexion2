    private void jButton1_REGISTRARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_REGISTRARActionPerformed
        // TODO add your handling code here:
         if(veriFyFields())
         {
        String nombre=jTextField1_NOMBRE.getText();
      
        String contrasena1=String.valueOf(jPasswordField1_CONTRASENA1.getPassword());
         String contrasena2=String.valueOf(jPasswordField2_CONTRASENA2.getPassword());
        String email=jTextField2_EMAIL.getText();
         String apellido=jTextField1_APELLIDO.getText();
         String telefono=jTextField1_TELEFONO.getText();
         String genero= "MASCULINO";
         
        String sha1="";
         
         try{
             MessageDigest digest= MessageDigest.getInstance("SHA-1");
            digest.reset();
            digest.update(contrasena1.getBytes("utf8"));
    sha1= String.format("%040x",new BigInteger(1,digest.digest()));
         
         }catch (Exception e){
         e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error real en el algoritmo de cifrado: " + e.getMessage());
        return;
         }
         if(jRadioButton2_FEMENINO.isSelected()){
            genero = "femenino";
         }
         if(imagen_path !=null){ 
                 //|| imagen_path.trim().isEmpty()){
             // JOptionPane.showMessageDialog(null,"por favor, selecione una iamgen","Imagen requerida",JOptionPane.WARNING_MESSAGE);
              //IIreturn;
        }
             
             controlador.users user;
      try{
          Path path=Paths.get(imagen_path);
             
                byte[]imagen= Files.readAllBytes(path);
      user = new controlador.users(1, nombre,apellido,sha1, email,telefono,genero,imagen);
      if (modelo.conexion_DB.getConnection() == null) {
                JOptionPane.showMessageDialog(null, "Error: No hay conexión con MySQL. Verifica que XAMPP esté encendido.");
                return; 
      }
      controlador.users.insertuser(user);
      //JOptionPane.showMessageDialog(null,"data inserted");
        
      } catch (Exception e){
      e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error en proceso de registro: " + e.getMessage());
      }  
         }    
  
         
    }//GEN-LAST:event_jButton1_REGISTRARActionPerformed

