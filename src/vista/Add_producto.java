      public void populateJTable() {
      controlador. productos productos= new controlador.productos();
    this.productosList=productos.productosList();
  // ArrayList<controlador.productos> productosList= productos.productosList();
   
    String[] colName={"id","nombre","precio", "descripcion","ubicacion"};
     
    Object[][] rows = new Object[productosList.size()][colName.length];
    
    DefaultTableModel model=(DefaultTableModel)jTable1_productos.getModel();
    
    for(int i=0; i<productosList.size();i++){
    rows[i][0]=productosList.get(i).getId();
    rows[i][1]=productosList.get(i).getNombre();
    rows[i][2]=productosList.get(i).getPrecio();
    rows[i][3]=productosList.get(i).getDescripcion();
    rows[i][4]=productosList.get(i).getUbicacion();
    }
    model.setDataVector(rows,colName);
   jTable1_productos.setModel(model);

    }

